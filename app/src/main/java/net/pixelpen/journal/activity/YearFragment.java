package net.pixelpen.journal.activity;

import android.content.Intent;
import android.os.Bundle;
import android.view.View;
import android.widget.AdapterView;
import android.widget.ArrayAdapter;
import android.widget.Spinner;
import android.widget.TextView;

import androidx.annotation.NonNull;
import androidx.recyclerview.widget.GridLayoutManager;
import androidx.recyclerview.widget.RecyclerView;

import net.pixelpen.journal.ApplicationObject;
import net.pixelpen.journal.R;
import net.pixelpen.journal.adapter.YearMonthAdapter;
import net.pixelpen.journal.model.Document;
import net.pixelpen.journal.model.YearOverview;

import java.io.File;
import java.util.ArrayList;
import java.util.List;

/**
 * The year at a glance.
 *
 * <p>The native form of the Year_Overview.html that year.py generated and a WebView displayed.
 * Same shape: a teal bar with the year and a category filter, a collapsible strip of highlights,
 * and the twelve months below, each listing the notes filed under the selected category.
 *
 * <p>A WebView is not used because the page had to be regenerated by hand, from a desktop, and
 * then copied onto the device -- which is why it stopped displaying properly after a change of
 * device. Reading the folders directly means it is simply correct whenever it is opened.
 */
public class YearFragment extends AutumnBaseFragment implements YearMonthAdapter.Listener {

    public static final String FRAGMENT_TAG = "YearFragment";

    public static YearFragment newInstance() {
        return new YearFragment();
    }

    @Override
    protected int getLayoutResId() {
        return R.layout.fragment_year;
    }

    @Override
    public String getFragmentTag() {
        return FRAGMENT_TAG;
    }

    private TextView _title;
    private TextView _back;
    private TextView _highlightsToggle;
    private View _highlights;
    private final TextView[] _slots = new TextView[YearOverview.HIGHLIGHT_SLOTS];
    private Spinner _categorySpinner;
    private RecyclerView _list;
    private YearMonthAdapter _adapter;

    private YearOverview _year;
    private boolean _highlightsOpen = true;
    /** Set while the spinner is being populated, so its callback does not count as a choice. */
    private boolean _settingUpSpinner;

    @Override
    public void onViewCreated(@NonNull final View view, final Bundle savedInstanceState) {
        super.onViewCreated(view, savedInstanceState);

        _title = view.findViewById(R.id.year_title);
        _back = view.findViewById(R.id.year_back);
        _highlightsToggle = view.findViewById(R.id.year_highlights_toggle);
        _highlights = view.findViewById(R.id.year_highlights);
        _slots[0] = view.findViewById(R.id.year_slot_1);
        _slots[1] = view.findViewById(R.id.year_slot_2);
        _slots[2] = view.findViewById(R.id.year_slot_3);
        _categorySpinner = view.findViewById(R.id.year_category);
        _list = view.findViewById(R.id.year_months);

        _adapter = new YearMonthAdapter(this);
        _list.setLayoutManager(new GridLayoutManager(requireContext(),
                getResources().getInteger(R.integer.year_month_columns)));
        _list.setAdapter(_adapter);
        _list.setItemAnimator(null);

        // Tapping the year folds the months away, and again brings them back.
        _title.setOnClickListener(v -> toggleAllMonths());
        _back.setOnClickListener(v -> showAllMonths());
        _highlightsToggle.setOnClickListener(v -> {
            _highlightsOpen = !_highlightsOpen;
            applyHighlightsVisibility();
        });

        _categorySpinner.setOnItemSelectedListener(new AdapterView.OnItemSelectedListener() {
            @Override
            public void onItemSelected(final AdapterView<?> parent, final View v,
                                       final int position, final long id) {
                if (_settingUpSpinner || _adapter == null) {
                    return;
                }
                _adapter.setCategory(String.valueOf(parent.getItemAtPosition(position)));
            }

            @Override
            public void onNothingSelected(final AdapterView<?> parent) {
            }
        });

        reload();
    }

    /**
     * Re-read the year and redraw.
     *
     * <p>Called when the tab becomes visible, so a note captured on the Calendar screen shows up
     * here without the fragment being recreated.
     */
    public void reload() {
        if (!isAdded() || _adapter == null) {
            return;
        }
        final File root = ApplicationObject.settings().getNotebookDirectory();
        new Thread(() -> {
            final File yearDir = YearOverview.latestYearDir(root);
            final YearOverview overview = (yearDir != null)
                    ? YearOverview.read(yearDir)
                    : YearOverview.empty(String.valueOf(java.util.Calendar.getInstance()
                            .get(java.util.Calendar.YEAR)));

            final android.app.Activity host = getActivity();
            if (host == null) {
                return;
            }
            host.runOnUiThread(() -> {
                if (!isAdded() || _adapter == null || _list == null) {
                    return;
                }
                _year = overview;
                apply(overview);
            });
        }).start();
    }

    private void apply(final YearOverview overview) {
        _title.setText(overview.year + "  ▼");

        // The selection is carried across a reload rather than reset, so capturing a note and
        // coming back here does not silently put the filter back to the default.
        final String previous = (_categorySpinner.getSelectedItem() == null)
                ? YearOverview.DEFAULT_CATEGORY
                : String.valueOf(_categorySpinner.getSelectedItem());

        _settingUpSpinner = true;
        final ArrayAdapter<String> cats = new ArrayAdapter<>(requireContext(),
                android.R.layout.simple_spinner_item, new ArrayList<>(overview.categories));
        cats.setDropDownViewResource(android.R.layout.simple_spinner_dropdown_item);
        _categorySpinner.setAdapter(cats);

        int index = overview.categories.indexOf(previous);
        if (index < 0) {
            index = overview.categories.indexOf(YearOverview.DEFAULT_CATEGORY);
        }
        if (index < 0) {
            index = 0;
        }
        _categorySpinner.setSelection(index, false);
        _settingUpSpinner = false;

        _adapter.setCategory(overview.categories.isEmpty()
                ? YearOverview.ALL_CATEGORIES : overview.categories.get(index));
        _adapter.setMonths(overview.months);

        applyHighlights(overview);
        applyHighlightsVisibility();
        _back.setVisibility(_adapter.getIsolated() >= 0 ? View.VISIBLE : View.GONE);
    }

    /**
     * Fill the three slots.
     *
     * <p>Three of them always, however many highlights exist. The original hid the strip entirely
     * when the folder was empty, which gave no hint that a year is meant to have highlights at
     * all; an empty slot is drawn dashed and says which number it is.
     */
    private void applyHighlights(final YearOverview overview) {
        final List<YearOverview.Event> hl = overview.highlights;
        for (int i = 0; i < _slots.length; i++) {
            final TextView slot = _slots[i];
            if (i < hl.size()) {
                final YearOverview.Event e = hl.get(i);
                slot.setText("📌  " + e.title);
                slot.setBackgroundResource(R.drawable.year_slot_filled);
                slot.setTextColor(androidx.core.content.ContextCompat.getColor(
                        requireContext(), R.color.tree_title));
                slot.setOnClickListener(v -> openNote(e.file));
            } else {
                slot.setText(getString(R.string.year_highlight_empty, i + 1));
                slot.setBackgroundResource(R.drawable.year_slot_empty);
                slot.setTextColor(androidx.core.content.ContextCompat.getColor(
                        requireContext(), R.color.year_slot_empty));
                slot.setOnClickListener(null);
                slot.setClickable(false);
            }
        }
    }

    private void applyHighlightsVisibility() {
        _highlights.setVisibility(_highlightsOpen ? View.VISIBLE : View.GONE);
        _highlightsToggle.setText(_highlightsOpen
                ? R.string.year_highlights_shown : R.string.year_highlights_hidden);
    }

    /** Fold every month away, or bring them all back. */
    private void toggleAllMonths() {
        if (_adapter.getIsolated() >= 0) {
            showAllMonths();
        } else {
            _list.setVisibility(_list.getVisibility() == View.VISIBLE ? View.GONE : View.VISIBLE);
        }
    }

    private void showAllMonths() {
        _adapter.setIsolated(-1);
        _list.setVisibility(View.VISIBLE);
        _back.setVisibility(View.GONE);
        _highlights.setVisibility(_highlightsOpen ? View.VISIBLE : View.GONE);
    }

    @Override
    public void onMonthTapped(final int index) {
        if (_adapter.getIsolated() == index) {
            showAllMonths();
            return;
        }
        // One month on its own, with the highlights out of the way: the point of isolating a
        // month is to see all of it, and the strip above is the first thing competing for room.
        _adapter.setIsolated(index);
        _list.setVisibility(View.VISIBLE);
        _back.setVisibility(View.VISIBLE);
        _highlights.setVisibility(View.GONE);
        _list.scrollToPosition(0);
    }

    @Override
    public void onEventTapped(final File file) {
        openNote(file);
    }

    private void openNote(final File file) {
        if (file == null || !file.isFile()) {
            return;
        }
        final Intent i = new Intent(requireContext(), DocumentActivity.class);
        i.putExtra(Document.EXTRA_FILE, file);
        i.putExtra(Document.EXTRA_DO_PREVIEW, true);
        startActivity(i);
    }

    /** Back leaves an isolated month before it leaves the app. */
    @Override
    public boolean onBackPressed() {
        if (_adapter != null && _adapter.getIsolated() >= 0) {
            showAllMonths();
            return true;
        }
        return false;
    }

    @Override
    public void onDestroyView() {
        _adapter = null;
        _list = null;
        super.onDestroyView();
    }
}
