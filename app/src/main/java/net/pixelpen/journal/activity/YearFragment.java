package net.pixelpen.journal.activity;

import android.content.Intent;
import android.os.Bundle;
import android.view.View;
import android.view.ViewGroup;
import android.widget.AdapterView;
import android.widget.ArrayAdapter;
import android.widget.Spinner;
import android.widget.TextView;

import androidx.annotation.NonNull;
import androidx.recyclerview.widget.GridLayoutManager;
import androidx.recyclerview.widget.RecyclerView;

import net.pixelpen.journal.ApplicationObject;
import net.pixelpen.journal.R;
import net.pixelpen.journal.adapter.YearMonthAdapter;
import net.pixelpen.journal.model.Document;
import net.pixelpen.journal.model.YearOverview;
import net.pixelpen.journal.util.NoteTimestamp;

import java.io.File;
import java.util.ArrayList;
import java.util.List;

/**
 * The year at a glance.
 *
 * <p>The native form of the Year_Overview.html that year.py generated and a WebView displayed.
 * Same shape: a teal bar with the year and a category filter, a collapsible strip of highlights,
 * and the twelve months below, each listing the notes filed under the selected category.
 *
 * <p>A WebView is not used because the page had to be regenerated by hand, from a desktop, and
 * then copied onto the device -- which is why it stopped displaying properly after a change of
 * device. Reading the folders directly means it is simply correct whenever it is opened.
 */
public class YearFragment extends AutumnBaseFragment implements YearMonthAdapter.Listener {

    public static final String FRAGMENT_TAG = "YearFragment";

    public static YearFragment newInstance() {
        return new YearFragment();
    }

    @Override
    protected int getLayoutResId() {
        return R.layout.fragment_year;
    }

    @Override
    public String getFragmentTag() {
        return FRAGMENT_TAG;
    }

    private TextView _title;
    private TextView _back;
    private TextView _highlightsToggle;
    private android.widget.LinearLayout _highlights;
    private Spinner _categorySpinner;
    private RecyclerView _list;
    private YearMonthAdapter _adapter;

    private YearOverview _year;
    private boolean _highlightsOpen = true;

    /**
     * The year being shown, or null to follow the newest.
     *
     * <p>Null by default, and it stays null unless a year is deliberately chosen. That way the
     * screen rolls over on its own at New Year: the first note captured in January creates the
     * folder, and the newest year becomes that one without anybody doing anything.
     */
    private String _selectedYear;
    /** Set while the spinner is being populated, so its callback does not count as a choice. */
    private boolean _settingUpSpinner;

    @Override
    public void onViewCreated(@NonNull final View view, final Bundle savedInstanceState) {
        super.onViewCreated(view, savedInstanceState);

        _title = view.findViewById(R.id.year_title);
        _back = view.findViewById(R.id.year_back);
        _highlightsToggle = view.findViewById(R.id.year_highlights_toggle);
        _highlights = view.findViewById(R.id.year_highlights);
        _categorySpinner = view.findViewById(R.id.year_category);
        _list = view.findViewById(R.id.year_months);

        _adapter = new YearMonthAdapter(this);
        _list.setLayoutManager(new GridLayoutManager(requireContext(),
                getResources().getInteger(R.integer.year_month_columns)));
        _list.setAdapter(_adapter);
        _list.setItemAnimator(null);

        // Tapping the year folds the months away, and again brings them back.
        // Tapping the year picks a year; the caret beside it has always looked like a picker and
        // now is one. Folding the months away moves to a long press, which is the lesser of the
        // two: without a picker, every year but the newest was simply unreachable here.
        _title.setOnClickListener(v -> promptPickYear());
        _title.setOnLongClickListener(v -> {
            toggleAllMonths();
            return true;
        });
        _back.setOnClickListener(v -> showAllMonths());
        _highlightsToggle.setOnClickListener(v -> {
            _highlightsOpen = !_highlightsOpen;
            applyHighlightsVisibility();
        });

        _categorySpinner.setOnItemSelectedListener(new AdapterView.OnItemSelectedListener() {
            @Override
            public void onItemSelected(final AdapterView<?> parent, final View v,
                                       final int position, final long id) {
                if (_settingUpSpinner || _adapter == null) {
                    return;
                }
                _adapter.setCategory(String.valueOf(parent.getItemAtPosition(position)));
            }

            @Override
            public void onNothingSelected(final AdapterView<?> parent) {
            }
        });

        reload();
    }

    /**
     * Re-read the year and redraw.
     *
     * <p>Called when the tab becomes visible, so a note captured on the Calendar screen shows up
     * here without the fragment being recreated.
     */
    public void reload() {
        if (!isAdded() || _adapter == null) {
            return;
        }
        final File root = ApplicationObject.settings().getNotebookDirectory();
        final String wanted = _selectedYear;
        new Thread(() -> {
            File yearDir = null;
            if (wanted != null) {
                final File chosen = new File(root, wanted);
                if (chosen.isDirectory()) {
                    yearDir = chosen;
                }
            }
            // Falls back to the newest if the chosen year has gone -- renamed, moved, deleted --
            // rather than showing an empty screen for a folder that is not there any more.
            if (yearDir == null) {
                yearDir = YearOverview.latestYearDir(root);
            }
            final File resolved = yearDir;
            final YearOverview overview = (resolved != null)
                    ? YearOverview.read(resolved)
                    : YearOverview.empty(String.valueOf(java.util.Calendar.getInstance()
                            .get(java.util.Calendar.YEAR)));

            final android.app.Activity host = getActivity();
            if (host == null) {
                return;
            }
            host.runOnUiThread(() -> {
                if (!isAdded() || _adapter == null || _list == null) {
                    return;
                }
                _year = overview;
                apply(overview);
            });
        }).start();
    }

    private void apply(final YearOverview overview) {
        _title.setText(overview.year + "  ▼");

        // The selection is carried across a reload rather than reset, so capturing a note and
        // coming back here does not silently put the filter back to the default.
        final String previous = (_categorySpinner.getSelectedItem() == null)
                ? YearOverview.DEFAULT_CATEGORY
                : String.valueOf(_categorySpinner.getSelectedItem());

        _settingUpSpinner = true;
        // Closed state white-on-teal with a caret; the opened list stays the platform's own, which
        // is drawn on the popup's background rather than on the bar.
        final ArrayAdapter<String> cats = new ArrayAdapter<>(requireContext(),
                R.layout.item_year_spinner, new ArrayList<>(overview.categories));
        cats.setDropDownViewResource(android.R.layout.simple_spinner_dropdown_item);
        _categorySpinner.setAdapter(cats);

        int index = overview.categories.indexOf(previous);
        if (index < 0) {
            index = overview.categories.indexOf(YearOverview.DEFAULT_CATEGORY);
        }
        if (index < 0) {
            index = 0;
        }
        _categorySpinner.setSelection(index, false);
        _settingUpSpinner = false;

        _adapter.setCategory(overview.categories.isEmpty()
                ? YearOverview.ALL_CATEGORIES : overview.categories.get(index));
        _adapter.setMonths(overview.months);

        applyHighlights(overview);
        applyHighlightsVisibility();
        _back.setVisibility(_adapter.getIsolated() >= 0 ? View.VISIBLE : View.GONE);
    }

    /**
     * Fill the three slots.
     *
     * <p>Three of them always, however many highlights exist. The original hid the strip entirely
     * when the folder was empty, which gave no hint that a year is meant to have highlights at
     * all; an empty slot is drawn dashed and says which number it is.
     */
    private void applyHighlights(final YearOverview overview) {
        final List<YearOverview.Event> hl = overview.highlights;
        final int rows = Math.max(YearOverview.HIGHLIGHT_SLOTS, hl.size());
        _highlights.removeAllViews();

        for (int i = 0; i < rows; i++) {
            final TextView slot = new TextView(requireContext());
            slot.setLayoutParams(new android.widget.LinearLayout.LayoutParams(
                    ViewGroup.LayoutParams.MATCH_PARENT, ViewGroup.LayoutParams.WRAP_CONTENT));
            final int pad = Math.round(8 * getResources().getDisplayMetrics().density);
            slot.setPadding(pad + pad / 4, pad, pad + pad / 4, pad);
            slot.setSingleLine(true);
            slot.setEllipsize(android.text.TextUtils.TruncateAt.END);
            slot.setTextSize(14f);
            final android.widget.LinearLayout.LayoutParams lp =
                    (android.widget.LinearLayout.LayoutParams) slot.getLayoutParams();
            lp.bottomMargin = Math.round(6 * getResources().getDisplayMetrics().density);

            if (i < hl.size()) {
                final YearOverview.Event e = hl.get(i);
                // The month alongside the title, so the order the strip is in is visible rather
                // than something the reader has to take on trust.
                final java.util.Calendar when = java.util.Calendar.getInstance();
                String label = "\uD83D\uDCCC  " + e.title;
                if (e.aboutMillis > 0L) {
                    when.setTimeInMillis(e.aboutMillis);
                    label = label + "   \u00B7   " + new java.text.SimpleDateFormat(
                            "MMM", java.util.Locale.getDefault()).format(when.getTime());
                }
                slot.setText(label);
                // Bold, as the original stylesheet had them: a highlight is the one thing on this
                // screen that is meant to carry weight. The empty slots stay plain, so the strip
                // reads as what is there rather than as room left over.
                slot.setTypeface(null, android.graphics.Typeface.BOLD);
                slot.setBackgroundResource(R.drawable.year_slot_filled);
                slot.setTextColor(androidx.core.content.ContextCompat.getColor(
                        requireContext(), R.color.tree_title));
                slot.setOnClickListener(v -> openNote(e.file));
            } else {
                slot.setText(getString(R.string.year_highlight_empty, i + 1));
                slot.setBackgroundResource(R.drawable.year_slot_empty);
                slot.setTextColor(androidx.core.content.ContextCompat.getColor(
                        requireContext(), R.color.year_slot_empty));
                slot.setOnClickListener(v -> promptNewHighlight());
            }
            _highlights.addView(slot);
        }
    }

    /**
     * Fill an empty highlight slot.
     *
     * <p>A highlight is an ordinary note in "Highlights &lt;year&gt;" beside the month folders,
     * which is where year.py looked for them, so one written here is also one that script would
     * have found.
     *
     * <p>It is seeded with the same date stamp on line 1 as a captured note. That stamp is what
     * the archive treats as the record of when something was written, and a note created by
     * another route without one is a note the ordering has nothing to read for.
     */
    private void promptNewHighlight() {
        final YearOverview overview = _year;
        if (overview == null || overview.highlightsDir() == null) {
            return;
        }
        final android.widget.EditText input = new android.widget.EditText(requireContext());
        input.setInputType(android.text.InputType.TYPE_CLASS_TEXT
                | android.text.InputType.TYPE_TEXT_FLAG_CAP_SENTENCES);
        input.setHint(R.string.year_highlight_hint);

        new androidx.appcompat.app.AlertDialog.Builder(requireContext())
                .setTitle(getString(R.string.year_highlight_new, overview.year))
                .setView(input)
                .setNegativeButton(android.R.string.cancel, null)
                .setPositiveButton(android.R.string.ok, (d, w) -> {
                    // Same sanitising as the capture screen, so a highlight cannot be given a name
                    // capture itself would never have produced.
                    final String title = input.getText().toString().trim()
                            .replaceAll("[\\\\/:*?\"<>|]", "_");
                    if (title.isEmpty()) {
                        return;
                    }
                    promptHighlightMonth(overview, title);
                })
                .show();
    }

    /**
     * Ask which month the highlight belongs to.
     *
     * <p>A month, not a date. This is the whole difficulty with highlights: they are a year-end
     * exercise, written once the year has a shape, so the order they are typed in has nothing to
     * do with the order things happened -- but you do not remember the day either. You remember
     * that the new app was late in the year and not in January. A date picker would force a day to
     * be invented, and that day then sits in the file reading as fact.
     *
     * <p>So: twelve choices, and the month is what gets written. Sequence without false precision,
     * and it matches how the archive is already laid out.
     */
    private void promptHighlightMonth(final YearOverview overview, final String title) {
        int year;
        try {
            year = Integer.parseInt(overview.year);
        } catch (final NumberFormatException e) {
            year = java.util.Calendar.getInstance().get(java.util.Calendar.YEAR);
        }
        final int pickedYear = year;

        final CharSequence[] months = new CharSequence[12];
        final java.util.Calendar c = java.util.Calendar.getInstance();
        for (int m = 0; m < 12; m++) {
            c.set(pickedYear, m, 1);
            months[m] = NoteTimestamp.formatMonth(c);
        }

        new androidx.appcompat.app.AlertDialog.Builder(requireContext())
                .setTitle(R.string.year_highlight_when)
                .setItems(months, (d, which) -> {
                    final java.util.Calendar about = java.util.Calendar.getInstance();
                    about.set(pickedYear, which, 1);
                    createHighlight(overview, title, about);
                })
                .setNegativeButton(android.R.string.cancel, null)
                .show();
    }

    private void createHighlight(final YearOverview overview, final String title,
                                 final java.util.Calendar about) {
        final File dir = overview.highlightsDir();
        if (dir == null) {
            return;
        }
        if (!dir.isDirectory() && !dir.mkdirs()) {
            toast(R.string.error_could_not_open_file);
            return;
        }
        final File note = new File(dir, title + ".md");
        if (note.exists()) {
            toast(R.string.file_folder_already_exists_please_use_a_different_name);
            return;
        }
        try {
            // A month stamp, not a full one. The day and time are not known and must not be
            // invented: written down they would read as fact to anything that came along later.
            final String stamp = NoteTimestamp.formatMonth(about);
            final java.io.FileOutputStream out = new java.io.FileOutputStream(note);
            try {
                out.write((stamp + "\n\n").getBytes("UTF-8"));
            } finally {
                out.close();
            }
        } catch (final Exception e) {
            toast(R.string.error_could_not_open_file);
            return;
        }
        // Reload before opening, so the slot is filled when the editor is dismissed.
        reload();
        // Edit, not preview: it was created a moment ago and holds nothing but its date stamp, so
        // there is nothing to preview and the point is to write in it.
        final Intent i = new Intent(requireContext(), DocumentActivity.class);
        i.putExtra(Document.EXTRA_FILE, note);
        startActivity(i);
    }

    private void toast(final int stringRes) {
        if (isAdded()) {
            android.widget.Toast.makeText(requireContext(), stringRes,
                    android.widget.Toast.LENGTH_SHORT).show();
        }
    }

    private void applyHighlightsVisibility() {
        _highlights.setVisibility(_highlightsOpen ? View.VISIBLE : View.GONE);
        _highlightsToggle.setText(_highlightsOpen
                ? R.string.year_highlights_shown : R.string.year_highlights_hidden);
    }

    /**
     * Choose which year to show.
     *
     * <p>Newest first, because the one wanted is nearly always recent. Choosing the newest clears
     * the selection rather than pinning it, so the screen goes back to following whatever the
     * newest year is and rolls over by itself next January.
     */
    private void promptPickYear() {
        final File root = ApplicationObject.settings().getNotebookDirectory();
        final java.util.List<File> years = YearOverview.yearDirs(root);
        if (years.size() < 2) {
            // Nothing to choose between; fall back to the other thing the header does.
            toggleAllMonths();
            return;
        }
        java.util.Collections.reverse(years);
        final CharSequence[] labels = new CharSequence[years.size()];
        for (int i = 0; i < years.size(); i++) {
            labels[i] = years.get(i).getName();
        }
        new androidx.appcompat.app.AlertDialog.Builder(requireContext())
                .setTitle(R.string.year_pick)
                .setItems(labels, (d, which) -> {
                    _selectedYear = (which == 0) ? null : years.get(which).getName();
                    reload();
                })
                .setNegativeButton(android.R.string.cancel, null)
                .show();
    }

    /** Fold every month away, or bring them all back. */
    private void toggleAllMonths() {
        if (_adapter.getIsolated() >= 0) {
            showAllMonths();
        } else {
            _list.setVisibility(_list.getVisibility() == View.VISIBLE ? View.GONE : View.VISIBLE);
        }
    }

    private void showAllMonths() {
        _adapter.setIsolated(-1);
        _list.setVisibility(View.VISIBLE);
        _back.setVisibility(View.GONE);
        _highlights.setVisibility(_highlightsOpen ? View.VISIBLE : View.GONE);
    }

    @Override
    public void onMonthTapped(final int index) {
        if (_adapter.getIsolated() == index) {
            showAllMonths();
            return;
        }
        // One month on its own, with the highlights out of the way: the point of isolating a
        // month is to see all of it, and the strip above is the first thing competing for room.
        _adapter.setIsolated(index);
        _list.setVisibility(View.VISIBLE);
        _back.setVisibility(View.VISIBLE);
        _highlights.setVisibility(View.GONE);
        _list.scrollToPosition(0);
    }

    @Override
    public void onEventTapped(final File file) {
        openNote(file);
    }

    private void openNote(final File file) {
        if (file == null || !file.isFile()) {
            return;
        }
        final Intent i = new Intent(requireContext(), DocumentActivity.class);
        i.putExtra(Document.EXTRA_FILE, file);
        i.putExtra(Document.EXTRA_DO_PREVIEW, true);
        startActivity(i);
    }

    /** Back leaves an isolated month before it leaves the app. */
    @Override
    public boolean onBackPressed() {
        if (_adapter != null && _adapter.getIsolated() >= 0) {
            showAllMonths();
            return true;
        }
        return false;
    }

    @Override
    public void onDestroyView() {
        _adapter = null;
        _list = null;
        super.onDestroyView();
    }
}
